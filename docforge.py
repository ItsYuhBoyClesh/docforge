"""DocForge: lightweight, local documentation inventory generator."""
from __future__ import annotations
import argparse
import ast
from pathlib import Path

SUFFIXES = {".py", ".js", ".ts", ".html", ".css", ".md"}
SKIP = {".git", ".venv", "venv", "node_modules", "__pycache__", "dist", "build"}

def scan(root: Path) -> list[tuple[str, list[str]]]:
    """Return relative source paths and top-level Python symbols."""
    root = root.resolve(strict=True)
    if not root.is_dir():
        raise ValueError("Project path must be a directory")
    items = []
    for path in sorted(root.rglob("*")):
        if path.is_symlink() or not path.is_file() or path.suffix.lower() not in SUFFIXES:
            continue
        rel = path.relative_to(root)
        if any(part.startswith(".") or part in SKIP for part in rel.parts[:-1]):
            continue
        symbols = []
        if path.suffix.lower() == ".py":
            try:
                if path.stat().st_size > 1_000_000:
                    symbols.append("(skipped large Python file)")
                else:
                    tree = ast.parse(path.read_text(encoding="utf-8"))
                    for node in tree.body:
                        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                            symbols.append(f"{type(node).__name__}: {node.name}")
            except (UnicodeError, SyntaxError, OSError) as exc:
                symbols.append(f"(could not parse: {type(exc).__name__})")
        items.append((rel.as_posix(), symbols))
    return items

def render(project: str, items: list[tuple[str, list[str]]]) -> str:
    lines = [f"# Project inventory: {project}", "", "Generated by DocForge (Open Heightz). Review before sharing.", "", "## Files", ""]
    for name, symbols in items:
        lines.append(f"- `{name.replace(chr(96), '')}`")
        lines.extend(f"  - {symbol}" for symbol in symbols)
    if not items:
        lines.append("_No supported source files found._")
    return "\n".join(lines) + "\n"

def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a local Markdown project inventory")
    parser.add_argument("project", type=Path, help="Source directory")
    parser.add_argument("--output", type=Path, default=Path("PROJECT_OVERVIEW.md"))
    parser.add_argument("--force", action="store_true", help="Overwrite existing output")
    args = parser.parse_args()
    output = args.output.resolve()
    if output.exists() and not args.force:
        parser.error("Output already exists; specify --force to replace it")
    try:
        inventory = scan(args.project)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(args.project.resolve().name, inventory), encoding="utf-8")
    print(f"Documented {len(inventory)} files to {output}")

if __name__ == "__main__":
    main()
